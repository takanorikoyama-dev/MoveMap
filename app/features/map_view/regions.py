def medal_for_rank(rank: int) -> str:
    """順位 → 金/銀/銅メダル絵文字、4 位以下は番号文字列."""
    if rank == 1:
        return "🥇"
    if rank == 2:
        return "🥈"
    if rank == 3:
        return "🥉"
    return f"{rank}"


def region_of(pref_code: str) -> str:
    """都道府県コード → 地方ブロック名."""
    return PREFECTURE_REGIONS.get(pref_code, "")


